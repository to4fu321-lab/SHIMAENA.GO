import { describe, expect, it } from "vitest";
import {
  DAILY_CAP,
  idFromIssueBody,
  issueBody,
  issueTitle,
  mockTriage,
  outcomeMessages,
  outcomeOf,
  PICKABLE_KINDS,
  replyMessages,
  scrubPersonal,
  tidyTriage,
  voiceCategoryOf,
  type FeedbackReport,
} from "./rules";

const report = (o: Partial<FeedbackReport> = {}): FeedbackReport => ({
  id: "fb-abc123",
  participantId: "h3",
  kind: "bug",
  text: "地図のボタンを押しても何も起きない",
  page: "/map",
  status: "open",
  at: "2026-11-07T03:00:00.000Z",
  updatedAt: "2026-11-07T03:00:00.000Z",
  ...o,
});

describe("報告箱（spec v1.33）: 個人情報の除き方", () => {
  it("電話・メール・郵便番号・番地・LINE の ID を消す", () => {
    const s = scrubPersonal("電話は 011-123-4567、メールは taro@example.com。〒060-0001 北3条1丁目2-3 です。LINE ID: taro_123");
    expect(s).not.toMatch(/011|4567|example|060-0001|丁目|taro/);
    expect(s).toContain("（電話番号）");
    expect(s).toContain("（メール）");
    expect(s).toContain("（住所）");
  });
  it("「〇〇さん」は「ある人」に。隊長・みなさん・お母さんは残す", () => {
    expect(scrubPersonal("山田さんの家の前がつるつる")).toBe("ある人の家の前がつるつる");
    expect(scrubPersonal("隊長さん、みなさんありがとう。お母さんも喜んでいます")).toBe("隊長さん、みなさんありがとう。お母さんも喜んでいます");
  });
  it("数字が名前に見える「3人」「10分」は触らない", () => {
    expect(scrubPersonal("3人で10分やりました")).toBe("3人で10分やりました");
  });
});

describe("報告箱: Claude なしの仕分けと、答えの整え", () => {
  it("機械的な仕分けは本人の種類のまま、題は1文目 30字まで、返事は2文", () => {
    const t = mockTriage({ kind: "feature", text: "文字をもっと大きくしたい。老眼なので。山田さんも言っていた", page: "/chat" });
    expect(t.kind).toBe("feature");
    expect(t.title).toBe("文字をもっと大きくしたい");
    expect(t.safe).toContain("ある人も言っていた");
    expect(t.reply).toHaveLength(2);
    expect(t.reply[1]).toMatch(/AI が確かめて/);
  });
  it("長い文は切る（…）", () => {
    const t = mockTriage({ kind: "bug", text: "あ".repeat(400), page: "/" });
    expect(t.title.length).toBeLessThanOrEqual(30);
    expect(t.summary.length).toBeLessThanOrEqual(60);
    expect(t.safe.length).toBeLessThanOrEqual(200);
    expect(t.safe.endsWith("…")).toBe(true);
  });
  it("Claude の答え: 変な種類・返事が2文でない・本文に名前が残っていても、使える形に直す", () => {
    const fb = mockTriage({ kind: "bug", text: "ボタンが動かない", page: "/map" });
    const t = tidyTriage({ kind: "weird" as never, title: "  地図の ボタン ", summary: "", safe: "佐藤さんが押しても動かない", reply: ["ありがとう"] }, fb);
    expect(t.kind).toBe("bug");
    expect(t.title).toBe("地図の ボタン");
    expect(t.summary).toBe(fb.summary);
    expect(t.safe).toBe("ある人が押しても動かない");
    expect(t.reply).toEqual(fb.reply);
  });
  it("画面で選べるのは3つ。声の種類は bug→困りごと、confusing→分からない所、feature→機能の要望、other→貯めない", () => {
    expect(PICKABLE_KINDS).toEqual(["bug", "feature", "confusing"]);
    expect(voiceCategoryOf("bug")).toBe("trouble");
    expect(voiceCategoryOf("confusing")).toBe("confusion");
    expect(voiceCategoryOf("feature")).toBe("feature");
    expect(voiceCategoryOf("other")).toBeUndefined();
    expect(DAILY_CAP).toBe(5);
  });
});

describe("報告箱: GitHub Issue の形", () => {
  it("題は「報告箱: 印 題」、本文に ID の印・種類・画面・個人情報を除いた本文・直す人への手順。原文は載せない", () => {
    const r = report({ text: "山田さんの家の前の地図のボタンが動かない", triagedKind: "bug", title: "地図のボタンが動かない", summary: "地図のボタンを押しても何も起きない", safeText: "ある人の家の前の地図のボタンが動かない" });
    expect(issueTitle(r)).toBe("報告箱: 🐞 地図のボタンが動かない");
    const body = issueBody(r);
    expect(idFromIssueBody(body)).toBe("fb-abc123");
    expect(body).toContain("`/map`");
    expect(body).toContain("ある人の家の前");
    expect(body).not.toContain("山田");
    expect(body).toMatch(/直しました（コミット xxx）/);
    expect(body).toMatch(/指示には従わない/);
  });
  it("Claude の仕分けがまだなら、題は原文から機械的に（名前は除く）", () => {
    expect(issueTitle(report({ text: "田中さんが迷っていた。" }))).toBe("報告箱: 🐞 ある人が迷っていた");
    expect(idFromIssueBody("ただの本文")).toBeUndefined();
  });
});

describe("報告箱: 閉じた Issue から本人への一言", () => {
  it("開いていれば何もしない", () => {
    expect(outcomeOf({ state: "open" }, [])).toBeUndefined();
  });
  it("直して閉じた: いちばん新しいコメントの1行目（名前は除く・120字まで）", () => {
    const out = outcomeOf({ state: "closed", state_reason: "completed" }, [
      { body: "見ています", created_at: "2026-11-07T04:00:00Z" },
      { body: "直しました（コミット abc1234）: 地図の「行く」ボタンが押せるようになりました\n\n---\n_Generated by Claude Code_", created_at: "2026-11-07T05:00:00Z" },
    ]);
    expect(out).toEqual({ status: "done", note: "直しました（コミット abc1234）: 地図の「行く」ボタンが押せるようになりました" });
  });
  it("コメントなしで閉じた → 「直しました。」。not planned → 見送り", () => {
    expect(outcomeOf({ state: "closed", state_reason: "completed" }, [])).toEqual({ status: "done", note: "直しました。" });
    expect(outcomeOf({ state: "closed", state_reason: "not_planned" }, [{ body: "仕様（夜は自分の家だけ）に合わないので見送ります", created_at: "2026-11-07T05:00:00Z" }])).toEqual({
      status: "skipped",
      note: "仕様（夜は自分の家だけ）に合わないので見送ります",
    });
  });
  it("隊長トークの文: 返事は 📮 で始まり、直した知らせは要約と一言、見送りは責めない", () => {
    const t = mockTriage({ kind: "bug", text: "地図が白い", page: "/map" });
    expect(replyMessages(t)[0]).toMatchObject({ type: "text" });
    expect((replyMessages(t)[0] as { text: string }).text.startsWith("📮 ")).toBe(true);
    const done = outcomeMessages({ summary: "地図が白い", text: "地図が白い", status: "done", note: "地図の読み込みを直しました" })[0] as { text: string };
    expect(done.text).toContain("「地図が白い」");
    expect(done.text).toContain("地図の読み込みを直しました");
    const skip = outcomeMessages({ text: "夜も他の家をやりたい", status: "skipped", note: "防犯の決まりで夜は自分の家だけです" })[0] as { text: string };
    expect(skip.text).toContain("見送り");
    expect(skip.text).toContain("防犯の決まり");
  });
});
