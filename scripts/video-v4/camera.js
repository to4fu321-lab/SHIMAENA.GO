const CAM_CUTS = TL.scenes.map((s) => s.start).filter((t) => t > 0.1);
/** その秒のカメラ（中心と倍率）。場面の頭は、すこし寄ってから落ち着く */
function cameraAt(t) {
  const P = CAM_PTS;
  let x = 960, y = 540, z = 1;
  if (t <= P[0][0]) [, x, y, z] = P[0];
  else if (t >= P[P.length - 1][0]) [, x, y, z] = P[P.length - 1];
  else for (let i = 1; i < P.length; i++) if (t <= P[i][0]) {
    const a = P[i - 1], b = P[i], gap = b[0] - a[0];
    // 場面をまたぐ所（点と点が 0.2 秒より近い）は、切り替える。それ以外は、なめらかにつなぐ
    const k = gap < 0.2 ? (t - a[0] >= gap / 2 ? 1 : 0) : Ease.io((t - a[0]) / gap);
    x = lerp(a[1], b[1], k); y = lerp(a[2], b[2], k); z = lerp(a[3], b[3], k);
    break;
  }
  for (const c of CAM_CUTS) { const d = t - c; if (d >= 0 && d < 0.8) z *= 1 + 0.05 * Math.exp(-d * 6); }
  // 絵の外が見えないように、中心を内側に寄せる
  x = clamp(x, 960 / z, 1920 - 960 / z); y = clamp(y, 540 / z, 1080 - 540 / z);
  return { x, y, z };
}
function applyCamera(root, t) {
  const c = cameraAt(t);
  root.style.transformOrigin = "0 0";
  const tx = 960 - c.x * c.z, ty = 540 - c.y * c.z;
  root.style.transform = `translate(${tx.toFixed(2)}px,${ty.toFixed(2)}px) scale(${c.z.toFixed(4)})`;
  // 画面の端に置く表示（3つの仕事・10分の時計）は、カメラと一緒に動かさない（逆向きに戻す）
  for (const h of (root._hud ??= [...root.querySelectorAll(".hud")])) { h.style.transformOrigin = "0 0"; h.style.transform = `scale(${(1 / c.z).toFixed(5)}) translate(${(-tx).toFixed(2)}px,${(-ty).toFixed(2)}px)`; }
}
